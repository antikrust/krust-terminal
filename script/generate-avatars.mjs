#!/usr/bin/env node
// Regenerates the bundled avatar set in app/assets/bundled/avatars/.
//
// Avatars are DiceBear art (https://www.dicebear.com/) plus the "animals" set
// written for the wildcard site. Both are *deterministic*: a (style, seed) pair
// always renders the same picture, which is why an account only needs to store
// those two short strings rather than an image.
//
// We pre-render rather than generating at runtime for two reasons: DiceBear is
// a JavaScript library and this app is Rust, and a bundled set keeps avatars
// working with no network and no dependency on wildcard staying up.
//
// Usage (needs node and a one-off dependency install). Node resolves bare
// imports relative to the *script*, so the script has to sit beside the
// installed dependencies — hence copying it out and passing the repo path:
//
//   mkdir -p /tmp/avatars && cd /tmp/avatars
//   npm pkg set type=module
//   npm install @dicebear/core@^9.4.2 @dicebear/collection@^9.4.2
//   cp ~/github/wildcard/server/avatars/animals.js .
//   cp <repo>/script/generate-avatars.mjs .
//   node generate-avatars.mjs <repo>
//
// LICENSING: every DiceBear style is © its artist under CC0, CC BY 4.0, or a
// free-for-commercial licence. Because we redistribute the art, CC BY styles
// legally require attribution — see app/assets/bundled/avatars/LICENSES.md and
// the credit rendered on the About page. If you add a style here, add its
// licence line there too.

import { createAvatar } from '@dicebear/core';
import * as collection from '@dicebear/collection';
import { createAnimalAvatar } from './animals.js';
import { mkdirSync, writeFileSync, rmSync } from 'fs';
import { join, dirname } from 'path';
import { fileURLToPath } from 'url';

// Repo root: first argument, else this script's parent directory (which works
// when it is run in place, but not when copied beside its dependencies).
const REPO = process.argv[2] ?? join(dirname(fileURLToPath(import.meta.url)), '..');
const OUT = join(REPO, 'app/assets/bundled/avatars');

// The same sets the wildcard picker offers, in the same order. `animals` is
// ours; the rest are DiceBear collection styles keyed by their camelCase export.
const STYLES = [
  { id: 'bottts', label: 'Robots' },
  { id: 'animals', label: 'Animals' },
  { id: 'adventurer', label: 'Adventurer' },
  { id: 'avataaars', label: 'Avataaars' },
  { id: 'big-ears', label: 'Big Ears' },
  { id: 'big-smile', label: 'Big Smile' },
  { id: 'croodles', label: 'Croodles' },
  { id: 'fun-emoji', label: 'Fun Emoji' },
  { id: 'lorelei', label: 'Lorelei' },
  { id: 'micah', label: 'Micah' },
  { id: 'miniavs', label: 'Miniavs' },
  { id: 'notionists', label: 'Notionists' },
  { id: 'open-peeps', label: 'Open Peeps' },
  { id: 'personas', label: 'Personas' },
  { id: 'pixel-art', label: 'Pixel Art' },
  { id: 'thumbs', label: 'Thumbs' },
];

// Twelve variants per style: enough to feel like a choice, small enough that
// the whole set stays a rounding error in the binary. Seeds are stable ids —
// changing one changes everybody's avatar who picked it, so don't.
const SEEDS = Array.from({ length: 12 }, (_, i) => String(i + 1).padStart(2, '0'));

const camel = (s) => s.replace(/-([a-z])/g, (_, c) => c.toUpperCase());

function render(styleId, seed) {
  if (styleId === 'animals') return createAnimalAvatar(seed);
  const style = collection[camel(styleId)];
  if (!style) throw new Error(`unknown DiceBear style: ${styleId}`);
  return createAvatar(style, { seed }).toString();
}

rmSync(OUT, { recursive: true, force: true });

// DiceBear embeds a Dublin Core rights statement in every SVG it renders.
// That is the authoritative attribution for a style, so harvest it rather
// than maintaining a hand-written (and quietly rotting) table.
function rightsOf(svg) {
  const match = svg.match(/<dc:rights>(.*?)<\/dc:rights>/s);
  if (!match) return null;
  return match[1].replace(/<[^>]+>/g, ' ').replace(/\s+/g, ' ').trim();
}

let count = 0;
let bytes = 0;
const manifest = [];
const rights = [];

for (const { id, label } of STYLES) {
  mkdirSync(join(OUT, id), { recursive: true });
  const entries = [];
  let firstSvg = null;
  for (const seed of SEEDS) {
    const svg = render(id, seed);
    writeFileSync(join(OUT, id, `${seed}.svg`), svg);
    firstSvg ??= svg;
    entries.push(seed);
    count += 1;
    bytes += Buffer.byteLength(svg);
  }
  manifest.push({ id, label, seeds: entries });
  rights.push({ id, label, rights: rightsOf(firstSvg) });
}

const licenses = `# Avatar art licences

Generated by script/generate-avatars.mjs — do not edit by hand.

The avatars bundled in this directory are third-party artwork redistributed
with this application. Each entry below is the rights statement embedded by
[DiceBear](https://www.dicebear.com/) in the artwork itself.

**Several of these are CC BY 4.0, which makes attribution a licence
condition, not a courtesy.** The credit is rendered in the app on the About
page (\`app/src/settings_view/about_page.rs\`). If you add or remove a style,
regenerate this file and check that page still lists what it must.

${rights
  .map(({ id, label, rights }) =>
    rights
      ? `## ${label} (\`${id}\`)\n\n${rights}\n`
      : `## ${label} (\`${id}\`)\n\nOriginal work for this project (the wildcard "AirVent Animals" set); no third-party licence applies.\n`,
  )
  .join('\n')}
## The generator

DiceBear's own library (\`@dicebear/core\`, \`@dicebear/collection\`) is MIT
licensed. It is a build-time dependency only — it is not distributed with the
application, which ships the rendered SVGs above.
`;

writeFileSync(join(OUT, 'LICENSES.md'), licenses);

// The Rust side needs &'static str paths (AssetSource::Bundled), so emit the
// table rather than hand-maintaining 192 string literals.
const rust = `//! Generated by script/generate-avatars.mjs — do not edit by hand.
//!
//! The bundled avatar set: DiceBear art plus the wildcard "animals" style,
//! pre-rendered because DiceBear is a JavaScript library and these need to
//! work offline. An avatar is identified by (style, seed); the SVG bytes are
//! embedded via [\`warp_assets\`].
//!
//! Attribution obligations live in app/assets/bundled/avatars/LICENSES.md and
//! are surfaced on the About page.

/// One selectable art style, with the seeds bundled for it.
pub struct AvatarStyle {
    /// Stable id stored on the account, e.g. \`"bottts"\`.
    pub id: &'static str,
    /// Name shown in the picker.
    pub label: &'static str,
    /// \`(seed, bundled asset path)\` pairs, in picker order.
    pub variants: &'static [(&'static str, &'static str)],
}

/// Every bundled style, in the order the picker shows them.
pub const STYLES: &[AvatarStyle] = &[
${manifest
  .map(
    ({ id, label, seeds }) => `    AvatarStyle {
        id: ${JSON.stringify(id)},
        label: ${JSON.stringify(label)},
        variants: &[
${seeds
  .map((s) => `            (${JSON.stringify(s)}, "bundled/avatars/${id}/${s}.svg"),`)
  .join('\n')}
        ],
    },`,
  )
  .join('\n')}
];
`;

writeFileSync(join(REPO, 'app/src/ui_components/avatar_set.rs'), rust);

console.log(
  `wrote ${count} avatars across ${STYLES.length} styles (${(bytes / 1024).toFixed(0)} KiB) to ${OUT}`,
);
